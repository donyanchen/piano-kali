#!/usr/bin/env python3
"""Extract a DSI panel's init/brightness/DSC payloads straight from a DTB.

    python3 scripts/extract-panel-seq.py piano-real.dtb mdss_dsi_p81_35_02_0b \
            --out kernel/drivers/gpu/drm/panel/panel-xiaomi-p81 --c-header

Reading the DTB with `fdtget` instead of parsing `dtc -O dts` text: the vendor
DTS is 42k lines with commands wrapped over many lines and stored both as byte
arrays and as 32-bit cells, and a text parser silently loses sync. fdtget gives
the exact bytes the device boots with.

Layout assumed (piano factory layout, see docs/KERNEL-TRUTH.md §3.1):
    /soc/qcom,mdss_mdp@ae00000/<panel>/
        qcom,mdss-dsi-display-timings/timing@<fps>/...

Output: <out>/<panel>.json + optional <panel>.h with one array per payload.
The bytes are hardware data from the factory DT, not third-party kernel code.
"""
import argparse
import json
import os
import re
import subprocess
import sys

MDSS = '/soc/qcom,mdss_mdp@ae00000'
FPS_CANDIDATES = [30, 48, 50, 60, 72, 90, 120, 144, 165, 180]


def fdtget(dtb, path, prop=None, t='bx'):
    cmd = ['fdtget', '-t', t, dtb, path]
    if prop:
        cmd.append(prop)
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        return None
    return r.stdout.strip()


def fdtget_list(dtb, path, mode):
    r = subprocess.run(['fdtget', mode, dtb, path], capture_output=True, text=True)
    return r.stdout.split() if r.returncode == 0 else []


def list_props(dtb, path):
    return fdtget_list(dtb, path, '-p')


def list_children(dtb, path):
    return fdtget_list(dtb, path, '-l')


def read_bytes(dtb, path, prop):
    """Byte payload of a property, or None if it is not a byte array."""
    out = fdtget(dtb, path, prop, 'bx')
    if out is None:
        return None
    try:
        vals = [int(x, 16) for x in out.split()]
    except ValueError:
        return None
    # fdtget -t bx prints one value per byte; anything non-byte fails above.
    if any(v > 0xff for v in vals):
        return None
    return vals


def read_cells(dtb, path, prop):
    out = fdtget(dtb, path, prop, 'x')
    if out is None:
        return None
    return [int(x, 16) for x in out.split()]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('dtb')
    ap.add_argument('panel', help='panel node name substring')
    ap.add_argument('--out', default='panel-data')
    ap.add_argument('--c-header', action='store_true')
    a = ap.parse_args()

    names = [n for n in list_children(a.dtb, MDSS) if a.panel in n]
    if not names:
        sys.exit('panel %r not found under %s' % (a.panel, MDSS))
    panel_path = MDSS + '/' + names[0]

    def is_payload(name):
        return name.endswith('-command') and not name.endswith('-state')

    props = list_props(a.dtb, panel_path)
    own = {}
    for p in props:
        if not is_payload(p):
            continue
        b = read_bytes(a.dtb, panel_path, p)
        if b:
            own[p] = b

    modes = {}
    timings_path = panel_path + '/qcom,mdss-dsi-display-timings'
    for child in list_children(a.dtb, timings_path):
        m = re.match(r'timing@(\d+)', child)
        if not m:
            continue
        rate = int(m.group(1))
        tpath = '%s/%s' % (timings_path, child)
        names = list_props(a.dtb, tpath)
        if not names:
            continue
        got = {}
        for p in names:
            if not is_payload(p):
                continue
            b = read_bytes(a.dtb, tpath, p)
            if b:
                got[p] = b
        if got:
            modes[str(rate)] = got
            w = read_cells(a.dtb, tpath, 'qcom,mdss-dsi-panel-width')
            h = read_cells(a.dtb, tpath, 'qcom,mdss-dsi-panel-height')
            modes[str(rate)]['_geometry'] = [w[0] if w else 0, h[0] if h else 0]

    os.makedirs(a.out, exist_ok=True)
    base = re.sub(r'[^A-Za-z0-9]+', '-', a.panel).strip('-')
    json.dump({'node': panel_path, 'properties': own, 'modes': modes},
              open(os.path.join(a.out, base + '.json'), 'w'), indent=1)

    print('node:', panel_path)
    for k, b in sorted(own.items()):
        print('  %-46s %4d B' % (k, len(b)))
    for m in sorted(modes, key=int):
        g = modes[m].get('_geometry')
        print('  [%s Hz] %sx%s' % (m, g[0], g[1]))
        for k, b in sorted(modes[m].items()):
            if k == '_geometry':
                continue
            print('    %-44s %4d B' % (k, len(b)))

    if a.c_header:
        ident = re.sub(r'[^A-Za-z0-9]', '_', a.panel).upper()
        hp = os.path.join(a.out, base + '.h')
        with open(hp, 'w') as fh:
            fh.write('/* Generated by scripts/extract-panel-seq.py from %s\n'
                     ' * Factory device-tree payloads (docs/KERNEL-TRUTH.md).\n */\n'
                     '#ifndef %s_H\n#define %s_H\n\n#include <linux/types.h>\n\n'
                     % (os.path.basename(a.dtb), ident, ident))

            def emit(name, data):
                fh.write('static const u8 %s[] = {\n' % name)
                for i in range(0, len(data), 12):
                    fh.write('\t' + ' '.join('0x%02x,' % x for x in data[i:i + 12]) + '\n')
                fh.write('};\n\n')

            for k, b in sorted(own.items()):
                emit(ident + '_' + re.sub(r'[^A-Za-z0-9]', '_', k).upper(), b)
            for m in sorted(modes, key=int):
                for k, b in sorted(modes[m].items()):
                    if k == '_geometry':
                        continue
                    emit('%s_%sHZ_%s' % (ident, m,
                                         re.sub(r'[^A-Za-z0-9]', '_', k).upper()), b)
            fh.write('#endif\n')
        print('header ->', hp)


if __name__ == '__main__':
    main()